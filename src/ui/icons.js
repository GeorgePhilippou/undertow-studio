// One-bit pixel icons drawn on a square grid.

const svg = (size, body) =>
  `<svg viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges" aria-hidden="true">${body}</svg>`;

// Rows of a bitmap: '#' is ink, '.' is paper, ' ' is transparent.
function bitmap(rows) {
  let body = '';
  rows.forEach((row, y) => {
    [...row].forEach((char, x) => {
      if (char === '#') body += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
      if (char === '.') body += `<rect x="${x}" y="${y}" width="1" height="1" fill="#fff"/>`;
    });
  });
  return svg(Math.max(rows.length, rows[0].length), body);
}

